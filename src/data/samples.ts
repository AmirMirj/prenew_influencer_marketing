export type CommentRow = {
  week?: string;
  post_date?: string;
  handle: string;
  region?: string;
  country?: string;
  sku?: string;
  timestamp: string;
  hashtags: string;
  text: string;
};

export function parseCsv(text: string): string[][] {
  return text
    .trim()
    .split(/\r?\n/)
    .map((line) => line.split(","))
    .filter((row) => row.length > 1);
}

export function loadRoiSample(csv = ROI_SAMPLE_CSV): RoiRow[] {
  const [header, ...rows] = parseCsv(csv);
  const index = Object.fromEntries(header.map((key, i) => [key, i]));
  return rows.map((row) => {
    const engagements = Number(row[index.engagements]);
    const reach = Number(row[index.reach]);
    return {
      week: row[index.week],
      post_date: row[index.post_date],
      handle: row[index.handle],
      region: row[index.region],
      country: row[index.country],
      sku: row[index.sku] || undefined,
      platform: row[index.platform],
      category: row[index.category],
      tier: row[index.tier],
      engagements,
      reach,
      views: Number(row[index.views]),
      attributed_sales: Number(row[index.attributed_sales]),
      engagement_rate: reach > 0 ? engagements / reach : 0,
    };
  });
}

export function loadPartsSample(csv = PARTS_DEMAND_CSV): PartsRow[] {
  const [header, ...rows] = parseCsv(csv);
  const index = Object.fromEntries(header.map((key, i) => [key, i]));
  return rows.map((row) => ({
    week: row[index.week],
    region: row[index.region],
    country: row[index.country],
    sku: row[index.sku] || undefined,
    cpu: Number(row[index.cpu] ?? 0),
    gpu: Number(row[index.gpu] ?? 0),
    ram: Number(row[index.ram] ?? 0),
    ssd: Number(row[index.ssd] ?? 0),
    units: index.units != null ? Number(row[index.units]) : undefined,
    price: index.price != null ? Number(row[index.price]) : undefined,
    campaign_window: Number(row[index.campaign_window]),
  }));
}

export function loadCommentSample(csv = COMMENTS_SAMPLE_CSV): CommentRow[] {
  const [header, ...rows] = parseCsv(csv);
  const index = Object.fromEntries(header.map((key, i) => [key, i]));
  return rows.map((row) => ({
    week: row[index.week],
    post_date: row[index.post_date],
    handle: row[index.handle],
    region: row[index.region],
    country: row[index.country],
    sku: row[index.sku] || undefined,
    timestamp: row[index.post_date] ?? row[index.timestamp],
    hashtags: row[index.hashtags],
    text: row.slice(index.text).join(","),
  }));
}
